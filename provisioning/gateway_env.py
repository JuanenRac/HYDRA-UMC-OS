"""HYDRA-UMC-GATEWAY-INDUSTRIAL/docker-compose.yml starts a production gateway and a production MQTT broker, and both refuse to start without secrets: the gateway needs
GATEWAY_JWT_SECRET, the broker needs credentials (MQTT_AUTH_JSON) and a topic ACL (MQTT_ACL_JSON). This script writes the `.env` that compose reads, with random values of this
device:

* GATEWAY_JWT_SECRET: 64 hex characters;
* one MQTT credential per machine bridge (username and client ID prefix `hydra-umc-bridge-<name>`, a random 24-character password) and the ACL rule of that identity
  (`hydra/bridges/<name>/#` to publish, `hydra/bridges/<name>/cmd/#` to subscribe). The bridge connects with HYDRA_MQTT_USERNAME / HYDRA_MQTT_PASSWORD of its credential
  (HYDRA-UMC-SDK's docs/BRIDGE_CONTRACT.md); the passwords are printed once, when the file is created.

An existing `.env` is never overwritten (its secrets stay), and the file is private (0600). Dry-run by default; `--apply` writes. Standard library only.
"""
from __future__ import annotations

import argparse
import json
import os
import secrets
import stat
import sys
from pathlib import Path

BRIDGES = ("cnc", "laser", "openpnp", "printer3d", "ros2", "amr")

# The AMR bridge speaks VDA 5050: its topics are {interfaceName}/{majorVersion}/..., with the
# interface name "vda5050" by default, not hydra/bridges/<name>/.
VDA5050_INTERFACE = "vda5050"


def build_env() -> tuple[str, dict[str, str]]:
    """The text of the .env and the bridge passwords (name -> password)."""
    credentials = []
    rules = []
    passwords: dict[str, str] = {}
    for name in BRIDGES:
        identity = f"hydra-umc-bridge-{name}"
        passwords[name] = secrets.token_urlsafe(18)
        credentials.append({"username": identity, "password": passwords[name], "clientIdPrefix": identity})
        if name == "amr":
            rules.append({"clientIdPrefix": identity, "publish": [f"{VDA5050_INTERFACE}/#"], "subscribe": [f"{VDA5050_INTERFACE}/#"]})
        else:
            rules.append({"clientIdPrefix": identity, "publish": [f"hydra/bridges/{name}/#"], "subscribe": [f"hydra/bridges/{name}/cmd/#"]})
    lines = [
        "# Generated by HYDRA-UMC-OS provisioning/gateway_env.py - private to this device (root, 0600). Do not commit.",
        f"GATEWAY_JWT_SECRET={secrets.token_hex(32)}",
        "MQTT_AUTH_JSON=" + json.dumps(credentials, separators=(",", ":")),
        "MQTT_ACL_JSON=" + json.dumps(rules, separators=(",", ":")),
        "",
    ]
    return "\n".join(lines), passwords


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("env_file", help="where to write the file: /etc/hydra-umc/gateway.env on a device (compose reads it with --env-file)")
    parser.add_argument("--apply", action="store_true", help="write the file (default: dry run)")
    args = parser.parse_args(argv)
    path = Path(args.env_file)
    if path.exists():
        print(f"GATEWAY_ENV=UNCHANGED {path} already exists: its secrets stay")
        return 0
    if not args.apply:
        print(f"[dry-run] would create {path} with GATEWAY_JWT_SECRET, MQTT_AUTH_JSON and MQTT_ACL_JSON for {', '.join(BRIDGES)}")
        return 0
    text, passwords = build_env()
    path.parent.mkdir(parents=True, exist_ok=True)
    handle = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, stat.S_IRUSR | stat.S_IWUSR)
    with os.fdopen(handle, "w", encoding="utf-8", newline="\n") as stream:
        stream.write(text)
    print(f"GATEWAY_ENV=CREATED {path}")
    print("  Each machine bridge connects with its own credential (shown ONCE; they are also in the root-only file):")
    for name, password in passwords.items():
        print(f"    hydra-umc-bridge-{name}: HYDRA_MQTT_USERNAME=hydra-umc-bridge-{name} HYDRA_MQTT_PASSWORD={password}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

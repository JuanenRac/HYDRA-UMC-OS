"""Writes the sudoers rule that lets the account of the updater run `hydra-umc-os deploy PROJECT --apply`, and nothing else, as root.

HYDRA-UMC-UPDATER runs the deployment through `sudo -n` when it is not root (docs/DEPLOY_CONTRACT.md) and its documentation says that the account needs a
sudoers rule which that project does not write. This tool writes it from the install plan: one line per project whose installer follows the deployment
contract this tool supports, each with the exact words of the command (the program, `deploy`, the repository name, `--apply`), so that sudo has no
wildcard to be talked into running something else (not `rollback`, not another argument, not a project the plan does not list).

    python tools/make_updater_sudoers.py            print the rule
    python tools/make_updater_sudoers.py --write    write provisioning/sudoers.d/hydra-umc-updater
    python tools/make_updater_sudoers.py --check    exit 1 when the committed file is not the one the plan produces

The file is not installed by default: `install_cm5_base.sh` copies it to /etc/sudoers.d only when `HYDRA_UMC_INSTALL_UPDATER_SUDOERS=1`, after `visudo -cf`.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PLAN = ROOT / "provisioning" / "install_plan.json"
TARGET = ROOT / "provisioning" / "sudoers.d" / "hydra-umc-updater"
ACCOUNT = "hydra-umc-updater"
PROGRAM = "/usr/local/bin/hydra-umc-os"
PROJECT = re.compile(r"HYDRA-UMC-[A-Z0-9]+(?:-[A-Z0-9]+)*")


def deployable_projects(plan: dict) -> list[str]:
    """The repositories whose installer follows the contract this tool supports, sorted and without repeats."""
    names = {
        row["source"]
        for row in plan["installers"]
        if row.get("source") and not row.get("deploy_exempt") and row.get("contract") == plan["supported_contract"] and PROJECT.fullmatch(row["source"])
    }
    return sorted(names)


def render(plan: dict, account: str = ACCOUNT) -> str:
    lines = [
        "# HYDRA-UMC-OS - what the account of the updater may run as root (generated by tools/make_updater_sudoers.py, do not edit)",
        "# Copyright (C) 2026 JuanenRac (Electro Hobby 3D) <electrohobby3d@gmail.com>",
        "# GPL-3.0-or-later - see LICENSE",
        "#",
        "# One line per project, with the exact words of the command: no wildcard, so `rollback`, another argument or another project is refused.",
        f"Defaults:{account} !requiretty",
    ]
    lines += [f"{account} ALL=(root) NOPASSWD: {PROGRAM} deploy {name} --apply" for name in deployable_projects(plan)]
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render(json.loads(PLAN.read_text(encoding="utf-8")))
    if args.write:
        TARGET.parent.mkdir(parents=True, exist_ok=True)
        TARGET.write_bytes(text.encode("utf-8"))
        print(f"wrote {TARGET.relative_to(ROOT)}")
        return 0
    if args.check:
        current = TARGET.read_bytes().decode("utf-8").replace("\r\n", "\n") if TARGET.is_file() else ""
        if current != text:
            print("UPDATER_SUDOERS=FAIL provisioning/sudoers.d/hydra-umc-updater is not what the install plan produces: run tools/make_updater_sudoers.py --write")
            return 1
        print(f"UPDATER_SUDOERS=PASS {len(deployable_projects(json.loads(PLAN.read_text(encoding='utf-8'))))} projects")
        return 0
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
